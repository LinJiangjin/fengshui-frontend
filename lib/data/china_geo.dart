/// 中国省市经纬度字典
///
/// 用途：命理排盘需要「出生地东经度数」做真太阳时校正（每 1° 约 4 分钟），
/// 让用户直接选地址、自动带出经度，避免手填数字出错。
///
/// 坐标为各行政区中心点的大致经纬度（WGS-84，保留两位小数），
/// 精度足够真太阳时校正使用（0.1° ≈ 24 秒）。出生地若靠近行政区边界，
/// 可用页面上的「手动微调」修正经度。
library;

/// 单个城市（或直辖市的区）的中心坐标
class CityCoord {
  const CityCoord(this.name, this.longitude, this.latitude);

  /// 城市 / 区名
  final String name;

  /// 东经度数（真）
  final double longitude;

  /// 北纬度数
  final double latitude;
}

/// 省级行政区 + 下辖城市
class ProvinceGeo {
  const ProvinceGeo(this.name, this.cities);

  final String name;
  final List<CityCoord> cities;
}

